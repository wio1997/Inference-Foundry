#!/usr/bin/env python3
"""Compare retained first-response text with an independent byte-level decode.

This does not execute a model or reproduce the exact installed Rust decoder.
It checks the actual stored response bytes against the frozen token IDs.
"""
import csv
import gzip
import hashlib
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]


def bytelevel_decoder(tokenizer):
    assert tokenizer['model']['type']=='BPE'
    assert tokenizer['decoder']['type']=='ByteLevel'
    vocabulary={index:text for text,index in tokenizer['model']['vocab'].items()}
    raw=list(range(33,127))+list(range(161,173))+list(range(174,256));encoded=raw[:];extra=0
    for value in range(256):
        if value not in raw:raw.append(value);encoded.append(256+extra);extra+=1
    inverse={chr(code):byte for byte,code in zip(raw,encoded)}
    def decode(ids):
        text=''.join(vocabulary[token] for token in ids)
        return bytes(inverse[c] for c in text).decode('utf8',errors='replace')
    return decode,vocabulary,inverse


def digest(text):return hashlib.sha256(text.encode('utf8')).hexdigest()


def main():
    tokenizer_path=ROOT.parent/'metadata/tokenizer.json'
    decode,vocabulary,inverse=bytelevel_decoder(json.loads(tokenizer_path.read_text()))
    cases=[];sources=[]
    for path in sorted((ROOT/'evidence/E33-L0-local-selected/runs').glob('**/*_details.jsonl')):
        sources.append(dict(path=str(path.relative_to(ROOT)),sha256=hashlib.sha256(path.read_bytes()).hexdigest()))
        rows=[json.loads(line) for line in path.read_text().splitlines()]
        for row in rows:
            extra=row['extra_details_data'];choices=extra['first_sse_payload']['choices'];assert len(choices)==1
            choice=choices[0];text=choice.get('text') or '';output_ids=choice.get('token_ids') or []
            if len(text)<4096:continue
            ids=extra['input_ids'];prompt_text=decode(ids);joined=decode(ids+output_ids)
            cases.append(dict(run_id=path.parent.name,logical_request_id=row['input'],first_output_token_ids=output_ids,
                              first_text_chars=len(text),first_text_sha256=digest(text),prompt_decoded_chars=len(prompt_text),
                              prompt_decoded_sha256=digest(prompt_text),prompt_plus_first_token_sha256=digest(joined),
                              exact_match_to_prompt_plus_first_token=text==joined,
                              exact_match_to_prompt_alone=text==prompt_text,prompt_prefix_1000_chars_match=text[:1000]==prompt_text[:1000],
                              first_output_byte_values=[inverse[c] for t in output_ids for c in vocabulary[t]],
                              original_prompt_ends_in_unicode_replacement=prompt_text.endswith('\ufffd'),
                              completed_text_ends_in_unicode_replacement=joined.endswith('\ufffd')))
    assert len(cases)==3 and all(c['logical_request_id']=='33' and c['first_output_token_ids']==[251] and c['exact_match_to_prompt_plus_first_token'] for c in cases)
    detailed=[]
    for p in sorted((ROOT/'evidence/E33-calibrated-census').glob('*/all-client-clocks.csv')):
        rows=list(csv.DictReader(p.open()));r=next(x for x in rows if x['logical_id']=='33')
        detailed.append(dict(run=p.parent.name,logical_request_id='33',first_payload_text_chars=int(r['first_payload_text_chars']),
                             first_payload_prompt_ids=int(r['first_payload_prompt_ids']),
                             all64_first_payload_json_reencoded_bytes=sum(int(x['first_payload_json_bytes']) for x in rows)))
    result=dict(scope='Retained real HTTP first-payload content plus independent byte-level decoding; no new inference or precision suite.',
                tokenizer_source=str(tokenizer_path),tokenizer_sha256=hashlib.sha256(tokenizer_path.read_bytes()).hexdigest(),
                source_details=sources,confirmed_cases=cases,detailed_capture_boundary_counts=detailed,
                installed_detokenizer_source='evidence/E33-installed-source-more/v1/v1/engine/detokenizer.py',
                confirmed='Request33 first SSE text includes the full decoded prompt plus one generated byte-token, not only newly generated text.',
                inference='A UTF-8 boundary in incremental detokenization is implicated: the prompt ends in a replacement character, and token251 completes its final multibyte character. Exact library-version replay is still required for the implementation root cause.',
                limits=['No causal service-time penalty is assigned from payload size alone.',
                        'Stored D1 CSVs record lengths only; exact text equality is established for the three original L0 real HTTP windows.',
                        'Input token IDs and native delivered output count remain frozen; this audit does not change or remove request33.'])
    target=ROOT/'data/E33-response-boundary-audit.json';target.write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n')
    print(json.dumps(dict(real_windows_verified=len(cases),request='33',native_first_output_ids=[251],first_text_chars=cases[0]['first_text_chars'],full_prompt_decode_match=True)))


if __name__=='__main__':main()
